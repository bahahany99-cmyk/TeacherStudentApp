#!/usr/bin/env python3
"""Inject the release signing config into the freshly scaffolded Android project.

Why a script instead of committed files?
`android/` is generated by `tool/scaffold_android.sh` and deliberately not tracked
(it must be reproducible). So the signing wiring is applied after scaffolding,
only when the keystore secrets are actually present.

Inputs (environment):
  DARSLY_KEYSTORE_BASE64  base64 of the PKCS12 keystore  (secret)
  DARSLY_STORE_PASSWORD   keystore password              (secret)
  DARSLY_KEY_ALIAS        key alias                      (default: darsly)
  DARSLY_KEY_PASSWORD     key password                   (default: store password)

If DARSLY_KEYSTORE_BASE64 is empty the script exits 0 and the build keeps
Flutter's default (debug-key signed release), which is fine for size measurement
and internal trials but must not be published.
"""

from __future__ import annotations

import base64
import os
import pathlib
import re
import sys

ANDROID_DIR = pathlib.Path('android')
APP_DIR = ANDROID_DIR / 'app'


def log(message: str) -> None:
    print(message, flush=True)


def notice(title: str, message: str) -> None:
    print(f'::notice title={title}::{message}', flush=True)


def fail(message: str) -> int:
    print(f'::error title=signing::{message}', flush=True)
    return 1


def find_gradle_file() -> pathlib.Path | None:
    for name in ('build.gradle.kts', 'build.gradle'):
        candidate = APP_DIR / name
        if candidate.exists():
            return candidate
    return None


KTS_SIGNING_BLOCK = """
    // ── توقيع الإصدار (يُضاف آليًا من tool/ci/apply_signing.py) ──────────────
    // كلمة المرور تُقرأ من android/key.properties الذي يُنشأ من أسرار CI فقط،
    // ولا يوجد أي سر في المستودع.
    // ⚠️ في Kotlin DSL يشير `java` إلى امتداد JavaPluginExtension لا إلى الحزمة،
    // فـ`java.util.Properties()` يفشل («Unresolved reference 'util'»). نستورد
    // الصنف أعلى الملف ونستخدمه باسمه (انظر ensure_kts_import).
    val keystoreProperties = Properties()
    val keystorePropertiesFile = rootProject.file("key.properties")
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { keystoreProperties.load(it) }
    }

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
                storeType = "PKCS12"
            }
        }
    }
"""

GROOVY_SIGNING_BLOCK = """
    // ── توقيع الإصدار (يُضاف آليًا من tool/ci/apply_signing.py) ──────────────
    def keystoreProperties = new Properties()
    def keystorePropertiesFile = rootProject.file('key.properties')
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.withInputStream { keystoreProperties.load(it) }
    }

    signingConfigs {
        release {
            if (keystorePropertiesFile.exists()) {
                storeFile file(keystoreProperties.getProperty('storeFile'))
                storePassword keystoreProperties.getProperty('storePassword')
                keyAlias keystoreProperties.getProperty('keyAlias')
                keyPassword keystoreProperties.getProperty('keyPassword')
                storeType = 'PKCS12'
            }
        }
    }
"""


KTS_PROPERTIES_IMPORT = 'import java.util.Properties'


def ensure_kts_import(source: str) -> str:
    """يضمن `import java.util.Properties` أعلى ملف Kotlin DSL.

    لماذا أعلى الملف؟ لأن الاستيرادات في Kotlin تسبق كل التصريحات (بما فيها
    `plugins { }`)، وتكرارها يُبقي الملف صالحًا عند إعادة الحقن.
    """
    if KTS_PROPERTIES_IMPORT in source:
        return source
    return KTS_PROPERTIES_IMPORT + '\n\n' + source


def patch(gradle: pathlib.Path) -> int:
    source = gradle.read_text(encoding='utf-8')
    is_kts = gradle.suffix == '.kts'

    if 'create("release")' in source or re.search(
        r'signingConfigs\s*\{[^}]*\brelease\s*\{', source
    ):
        notice('signing', 'ملف Gradle يحتوي إعداد توقيع مسبقًا — لا تعديل.')
        return 0

    anchor = 'buildTypes {'
    if anchor not in source:
        return fail(f'لم أجد «{anchor}» في {gradle}. لن أخمّن موضع الإدخال.')

    block = KTS_SIGNING_BLOCK if is_kts else GROOVY_SIGNING_BLOCK
    source = source.replace(anchor, block.strip('\n') + '\n\n    ' + anchor, 1)

    if is_kts:
        source = ensure_kts_import(source)

    # استبدال توقيع debug بتوقيع release داخل buildTypes.release فقط.
    patterns = (
        r'signingConfig\s*=\s*signingConfigs\.getByName\("debug"\)',
        r'signingConfig\s+signingConfigs\.debug',
        r'signingConfig\s*=\s*signingConfigs\.debug',
    )
    replaced = False
    for pattern in patterns:
        if re.search(pattern, source):
            replacement = (
                'signingConfig = signingConfigs.getByName("release")'
                if is_kts
                else 'signingConfig signingConfigs.release'
            )
            source = re.sub(pattern, replacement, source)
            replaced = True
            break

    if not replaced:
        return fail(
            'لم أجد سطر توقيع debug داخل buildTypes.release — '
            'شكل ملف Gradle تغيّر. راجع السكربت.'
        )

    gradle.write_text(source, encoding='utf-8')
    notice('signing', f'تم إدخال توقيع release في {gradle.name}')
    return 0


def main() -> int:
    if not ANDROID_DIR.exists():
        return fail('مجلد android غير موجود — يجب تشغيل scaffold_android.sh قبله.')

    encoded = os.environ.get('DARSLY_KEYSTORE_BASE64', '').strip()
    if not encoded:
        notice(
            'signing',
            'لا يوجد keystore في الأسرار — سيُبنى الإصدار بتوقيع debug (كافٍ للتجربة الداخلية فقط).',
        )
        return 0

    store_password = os.environ.get('DARSLY_STORE_PASSWORD', '')
    key_password = os.environ.get('DARSLY_KEY_PASSWORD', '') or store_password
    alias = os.environ.get('DARSLY_KEY_ALIAS', 'darsly')

    if not store_password:
        return fail('DARSLY_KEYSTORE_BASE64 موجود بلا DARSLY_STORE_PASSWORD.')

    # كلمة المرور داخل ملف الخصائص: لا تُطبع أبدًا في السجلات.
    keystore_path = APP_DIR / 'darsly-release.p12'
    keystore_path.write_bytes(base64.b64decode(encoded))
    keystore_path.chmod(0o600)

    # key.properties في android/ (مُستبعد من Git) بمفتاح storeFile تشير لملف p12.
    (ANDROID_DIR / 'key.properties').write_text(
        'storeFile=darsly-release.p12\n'
        f'storePassword={store_password}\n'
        f'keyAlias={alias}\n'
        f'keyPassword={key_password}\n',
        encoding='utf-8',
    )
    (ANDROID_DIR / 'key.properties').chmod(0o600)

    gradle = find_gradle_file()
    if gradle is None:
        return fail('لا build.gradle ولا build.gradle.kts في android/app.')

    status = patch(gradle)
    if status != 0:
        return status

    notice('signing', f'توقيع release جاهز. الحجم: {keystore_path.stat().st_size} بايت.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
