/// طلب بحث في قسم المدرسين يُرسَل من شاشة أخرى (الرئيسية مثلًا).
///
/// **لماذا كائن لا نص؟** لأن `ValueNotifier<String?>` لا يُبلّغ عند إسناد نفس
/// النص مرة أخرى؛ فلو بحث المستخدم عن «رياضيات» ثم عاد وبحث عنها ثانية لما وصل
/// الطلب. كل طلب هنا يحمل [sequence] متزايدًا، وهو حقل غير مضمَّن في `==`
/// (لا نتجاوز المشغّل)، فكل طلب **هوية جديدة** تُطلق إشعارًا.
///
/// الكائن **مستهلَك لمرة واحدة**: شاشة المدرسين تُطبّقه ثم تصفّر النوتیفاير،
/// فلا يُعاد تطبيقه عند كل إعادة بناء أو عند العودة للقسم لاحقًا.
class TeacherSearchRequest {
  const TeacherSearchRequest({required this.query, required this.sequence});

  /// نص البحث المطلوب (قد يكون فارغًا: «افتح البحث فقط»).
  final String query;

  /// ترتيب الطلب — للتمييز بين طلبين بنفس النص.
  final int sequence;

  @override
  String toString() => 'TeacherSearchRequest(#$sequence, "$query")';
}
