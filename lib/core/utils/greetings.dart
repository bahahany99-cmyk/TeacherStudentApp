/// نصوص الترحيب الذكية في الرئيسية (P25) — دالّة نقية قابلة للاختبار.
///
/// **لماذا دالّة لا `DateTime.now()` داخل الودجة؟** لأن نص الترحيب يتغيّر
/// بالساعة، والاختبار الذي يعتمد على الساعة الحقيقية ينجح صباحًا ويفشل مساءً.
/// هنا تُمرَّر الساعة، فتُغطّى كل الفترات الخمس بحالات حتمية.
abstract final class Greetings {
  /// عنوان الترحيب حسب ساعة اليوم (بتوقيت الجهاز المحلي).
  ///
  /// الفترات مختارة على سلوك الطالب المصري لا على تقسيم مثالي:
  /// - 4–11 صباحًا: «صباح الخير» (بداية اليوم الدراسي).
  /// - 11–16: «يومك سعيد» — بين المدرستين، وتحيّة الصباح تصبح متأخرة.
  /// - 16–20: «مساء الخير».
  /// - 20–24 و0–4: «سهرة موفّقة» — الوقت الذي يُراجَع فيه فعلًا.
  static String lineFor(DateTime now) {
    final int hour = now.hour;
    if (hour >= 4 && hour < 11) {
      return 'صباح الخير';
    }
    if (hour >= 11 && hour < 16) {
      return 'يومك سعيد';
    }
    if (hour >= 16 && hour < 20) {
      return 'مساء الخير';
    }
    return 'سهرة موفّقة';
  }

  /// جملة تحفيزية قصيرة تُعرض تحت الاسم — بلا وعود ولا أرقام مخترعة.
  static String subtitleFor(DateTime now) {
    final int hour = now.hour;
    if (hour >= 4 && hour < 11) {
      return 'ابدأ يومك بحصة تدفعك للأمام.';
    }
    if (hour >= 11 && hour < 16) {
      return 'وقت مناسب لحجز حصتك القادمة.';
    }
    if (hour >= 16 && hour < 20) {
      return 'راجع درس اليوم مع مدرّسك.';
    }
    return 'ليلة هادئة للمراجعة.';
  }
}
