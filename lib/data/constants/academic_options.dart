/// قوائم أكاديمية موحّدة (P19): المواد والمراحل والمحافظات.
///
/// **لماذا ثوابت مشتركة؟** لأن الحقول صارت قوائم منسدلة في نموذج ملف المدرس،
/// وأي إدخال حرّ كان يفتح الباب لقيم متشابهة حرفيًا مختلفة دلاليًا
/// («رياضيات» / «الرياضيات» / «رياضه»)، فتتفرّق نتائج البحث والفلترة بينها.
/// القائمة الواحدة تجعل ما يختاره المدرس هو نفسه ما يفلتر به الطالب.
///
/// **ملاحظة توافق:** البيانات الموجودة قبل هذا التغيير قد تحمل قيمًا ليست في
/// هذا القائمة (نص حر قديم أو مركّب مثل «الرياضيات — التفاضل»). لا نُعيد كتابة
/// بيانات أحد؛ الشاشات تُضيف القيمة القديمة كخيار إضافي عند التحرير، فتبقى
/// قابلة للعرض والحفظ بلا حذف صامت (انظر `AppSelectField.legacyValue`).
abstract final class AcademicOptions {
  /// المواد الدراسية الشائعة في المناهج المصرية.
  ///
  /// الترتيب مقصود: المواد الأساسية أولًا ثم الفروع العلمية ثم اللغات، حتى
  /// تكون الخيارات الأكثر استخدامًا في أول القائمة وأقل تمريرًا.
  static const List<String> subjects = <String>[
    'اللغة العربية',
    'الرياضيات',
    'العلوم',
    'اللغة الإنجليزية',
    'الدراسات الاجتماعية',
    'الفيزياء',
    'الكيمياء',
    'الأحياء',
    'الجيولوجيا',
    'اللغة الفرنسية',
    'اللغة الألمانية',
    'الرياضيات التطبيقية',
    'الفلسفة والمنطق',
    'علم النفس والاجتماع',
    'التربية الدينية',
    'الحاسب وتقنية المعلومات',
    'التربية الفنية',
    'التربية الرياضية',
  ];

  /// المراحل الدراسية.
  ///
  /// القيم مطابقة حرفيًا لما في البيانات التجريبية والاختبارات
  /// (`الابتدائية` / `الإعدادية` / `الثانوية العامة`)، فلا يظهر خيار «غير موجود
  /// في القائمة» لمستخدم حالي.
  static const List<String> stages = <String>[
    'الابتدائية',
    'الإعدادية',
    'الثانوية العامة',
    'الجامعة',
  ];

  /// محافظات مصر الـ27 بترتيبها الجغرافي الشائع (لا أبجديًا): من القاهرة
  /// والدلتا إلى الصعيد، وهو ما اعتاده المستخدم المصري في القوائم الرسمية.
  static const List<String> governorates = <String>[
    'القاهرة',
    'الجيزة',
    'القليوبية',
    'الإسكندرية',
    'البحيرة',
    'مطروح',
    'الغربية',
    'كفر الشيخ',
    'الدقهلية',
    'دمياط',
    'الشرقية',
    'المنوفية',
    'بورسعيد',
    'الإسماعيلية',
    'السويس',
    'شمال سيناء',
    'جنوب سيناء',
    'الفيوم',
    'بني سويف',
    'المنيا',
    'أسيوط',
    'سوهاج',
    'قنا',
    'الأقصر',
    'أسوان',
    'البحر الأحمر',
    'الوادي الجديد',
  ];

  /// هل القيمة ضمن المادة المعتمدة؟
  static bool isKnownSubject(String? value) =>
      value != null && subjects.contains(value.trim());

  /// هل القيمة ضمن المرحلة المعتمدة؟
  static bool isKnownStage(String? value) =>
      value != null && stages.contains(value.trim());

  /// هل القيمة ضمن المحافظات المعتمدة؟
  static bool isKnownGovernorate(String? value) =>
      value != null && governorates.contains(value.trim());

  /// خيارات المرحلة المقترحة في «بياناتي» (نفس المصدر، بلا نسخة ثانية).
  static List<String> get stageSuggestions => stages;
}
