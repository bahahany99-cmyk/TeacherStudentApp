/// قوائم أكاديمية موحّدة (P19): المواد والمراحل والمحافظات.
///
/// **لماذا ثوابت مشتركة؟** لأن الحقول صارت قوائم منسدلة في نموذج ملف المدرس،
/// وأي إدخال حرّ كان يفتح الباب لقيم متشابهة حرفيًا مختلفة دلاليًا
/// («رياضيات» / «الرياضيات» / «رياضه»)، فتتفرّق نتائج البحث والفلترة بينها.
/// القائمة الواحدة تجعل ما يختاره المدرس هو نفسه ما يفلتر به الطالب.
///
/// **ملاحظة توافق:** البيانات الموجودة قبل هذا التغيير قد تحمل قيمًا ليست في
/// هذا القائمة (نص حر قديم أو مركّب مثل «الرياضيات — التفاضل»). لا نُعيد كتابة
/// بيانات أحد؛ الشاشات تُضيف القيمة القديمة كخيار إضافي عند التحرير، فتبقى
/// قابلة للعرض والحفظ بلا حذف صامت (انظر `AppSelectField.legacyValue`).
abstract final class AcademicOptions {
  /// المواد الدراسية الشائعة في المناهج المصرية.
  ///
  /// الترتيب مقصود: المواد الأساسية أولًا ثم الفروع العلمية ثم اللغات، حتى
  /// تكون الخيارات الأكثر استخدامًا في أول القائمة وأقل تمريرًا.
  static const List<String> subjects = <String>[
    'اللغة العربية',
    'الرياضيات',
    'العلوم',
    'اللغة الإنجليزية',
    'الدراسات الاجتماعية',
    'الفيزياء',
    'الكيمياء',
    'الأحياء',
    'الجيولوجيا',
    'اللغة الفرنسية',
    'اللغة الألمانية',
    'الرياضيات التطبيقية',
    'الفلسفة والمنطق',
    'علم النفس والاجتماع',
    'التربية الدينية',
    'الحاسب وتقنية المعلومات',
    'التربية الفنية',
    'التربية الرياضية',
  ];

  /// المراحل الدراسية.
  ///
  /// القيم مطابقة حرفيًا لما في البيانات التجريبية والاختبارات
  /// (`الابتدائية` / `الإعدادية` / `الثانوية العامة`)، فلا يظهر خيار «غير موجود
  /// في القائمة» لمستخدم حالي.
  static const List<String> stages = <String>[
    'الابتدائية',
    'الإعدادية',
    'الثانوية العامة',
    'الجامعة',
  ];

  /// محافظات مصر الـ27 بترتيبها الجغرافي الشائع (لا أبجديًا): من القاهرة
  /// والدلتا إلى الصعيد، وهو ما اعتاده المستخدم المصري في القوائم الرسمية.
  static const List<String> governorates = <String>[
    'القاهرة',
    'الجيزة',
    'القليوبية',
    'الإسكندرية',
    'البحيرة',
    'مطروح',
    'الغربية',
    'كفر الشيخ',
    'الدقهلية',
    'دمياط',
    'الشرقية',
    'المنوفية',
    'بورسعيد',
    'الإسماعيلية',
    'السويس',
    'شمال سيناء',
    'جنوب سيناء',
    'الفيوم',
    'بني سويف',
    'المنيا',
    'أسيوط',
    'سوهاج',
    'قنا',
    'الأقصر',
    'أسوان',
    'البحر الأحمر',
    'الوادي الجديد',
  ];

  /// خيار «أخرى» في القوائم المنسدلة (P22).
  ///
  /// **قيمة حارسة لا تُحفظ أبدًا**: تُستخدم في الواجهة وحدها لتفعيل حقل الكتابة
  /// اليدوية. لو حُفظت لظهر في البحث اسم مادة لا معنى له.
  static const String customOption = '__custom__';

  /// نص الخيار كما يراه المدرس.
  static const String customOptionLabel = 'أخرى (كتابة يدوية / تخصيص)';

  /// أقصى طول للمادة أو المرحلة المخصّصة — نفس حدّ `firestore.rules`.
  ///
  /// الرقم مُوحَّد عمدًا في مكان واحد: الواجهة والقاعدة يقبلان/يرفضان نفس
  /// القيمة، فلا يحدث «قبِلت الواجهة ثم رفضها الخادم» أو العكس.
  static const int maxCustomLength = 40;

  /// الحد الأدنى (حرفان) — يمنع قيمة من حرف واحد لا تصف شيئًا.
  static const int minCustomLength = 2;

  /// هل هذه مادة مخصّصة (ليست من القائمة المعتمدة)؟
  ///
  /// تُستخدم عند تحميل ملف قديم: القيمة غير المعروفة تعني «النموذج يفتح على
  /// وضع الكتابة اليدوية مع تعبئة النص»، فيرى المدرس ما كتبه ويعدّله بلا فقدان.
  static bool isCustomSubject(String? value) =>
      value != null && value.trim().isNotEmpty && !isKnownSubject(value);

  /// هل هذه مرحلة مخصّصة؟
  static bool isCustomStage(String? value) =>
      value != null && value.trim().isNotEmpty && !isKnownStage(value);

  /// مشكلة في نص مخصّص (مادة أو مرحلة) — `null` يعني صالحًا.
  ///
  /// نفس الشروط حرفيًا في `firestore.rules` (`validProfilePayload`).
  static String? customTextProblem(String? raw, String label) {
    final String text = (raw ?? '').trim();
    if (text.isEmpty) {
      // «أدخل …» صياغة محايدة تصلح لكل التسميات (المادة، المرحلة، اسم المادة)
      // بخلاف «… مطلوب/مطلوبة» التي تختلف بحسب جنس الكلمة.
      return 'أدخل $label';
    }
    if (text.length < minCustomLength) {
      return 'طول $label قصير جدًا (حرفان على الأقل)';
    }
    if (text.length > maxCustomLength) {
      return 'طول $label يتجاوز الحد ($maxCustomLength حرفًا كحد أقصى)';
    }
    return null;
  }

  /// هل القيمة ضمن المادة المعتمدة؟
  static bool isKnownSubject(String? value) =>
      value != null && subjects.contains(value.trim());

  /// هل القيمة ضمن المرحلة المعتمدة؟
  static bool isKnownStage(String? value) =>
      value != null && stages.contains(value.trim());

  /// هل القيمة ضمن المحافظات المعتمدة؟
  static bool isKnownGovernorate(String? value) =>
      value != null && governorates.contains(value.trim());

  /// خيارات المرحلة المقترحة في «بياناتي» (نفس المصدر، بلا نسخة ثانية).
  static List<String> get stageSuggestions => stages;
}
