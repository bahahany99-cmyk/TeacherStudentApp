import 'package:teacher_student_app/data/models/app_user.dart';

/// سياسة **شاشة اختيار الصورة الإلزامية** للحساب الجديد (P31 — الإضافة الأخيرة).
///
/// ## لماذا سياسة منفصلة؟
/// لأن شرط الحجب قرار واحد يجب أن يُقرأ من مكان واحد: الهيكل الرئيسي
/// (`AppShell`) يسأله، والاختبارات تتحقق منه مباشرة. لو كُتب الشرط داخل ودجت
/// الشاشة لأصبح من السهل تجاوزه بتعديل موضع العرض.
///
/// ## الشرط بالضبط
/// تُعرض الشاشة إذا **تحقّق كل** ما يلي:
/// 1. يوجد مستخدم مسجّل، وليس جلسة معاينة (`isDemoAccount == false`).
/// 2. الدور دور مستخدم نهائي (طالب أو مدرّس) — جلسة الإدارة ليست حسابًا
///    جديدًا ولا تُحجب.
/// 3. لا يوجد `avatarPreset` محفوظ: الاختيار لم يُثبَّت بعد.
/// 4. الحساب **جديد**: تاريخ إنشائه معروف وليس قبل [cutover].
///
/// ## لماذا شرط التاريخ (4)؟
/// لأن الحسابات القديمة قد لا تحمل `avatarPreset` (ما قبل P22). الرسالة صريحة:
/// «لا تعرض هذه الشاشة للحسابات القديمة». والفاصل الزمني هو الطريقة الوحيدة
/// لتمييز القديم عن الجديد **بلا كتابة أي حقل جديد** على بيانات المستخدمين
/// القدامى ولا ترحيل قيمهم. الحساب الذي لا يحمل `createdAt` يُعامل كقديم
/// (لا حجب)، فلا يمكن أن يُقفل حساب موجود بسبب غياب حقل.
///
/// ## ما لا تفعله هذه السياسة
/// - لا تُعيّن صورة تلقائيًا ولا عشوائيًا: الاختيار يأتي من المستخدم وحده.
/// - لا تطلب عمرًا ولا جنسًا، ولا تفرض فئة على الطالب أو المدرّس: المعرض
///   كامل (30 صورة في عشر فئات) متاح للدورين.
abstract final class AvatarOnboardingPolicy {
  /// تاريخ بدء العمل بالشاشة: كل حساب أُنشئ بعده بلا اختيار محفوظ يُحجب حتى
  /// يختار. تاريخ ثابت (لا `DateTime.now`) كي تبقى النتيجة قابلة للاختبار
  /// وللشرح، ولا تتغيّر بتغيّر ساعة الجهاز.
  static final DateTime cutover = DateTime.utc(2026, 11, 1);

  /// هل يجب حجب التطبيق خلف شاشة اختيار الصورة لهذا المستخدم؟
  static bool isRequired(AppUser? user) {
    if (user == null) {
      return false;
    }
    if (user.isDemoAccount) {
      return false;
    }
    if (!user.role.isEndUser) {
      return false;
    }
    if (user.avatarPreset != null) {
      return false;
    }
    final DateTime? created = user.createdAt;
    if (created == null) {
      // حساب قديم أو مستند ناقص: لا نحجب حسابًا قائمًا أبدًا.
      return false;
    }
    return !created.isBefore(cutover);
  }
}
