import 'package:teacher_student_app/data/models/app_user.dart';
import 'package:teacher_student_app/data/models/user_avatar.dart';

/// سياسة **شاشة اختيار الصورة الإلزامية** للحساب الجديد (P31).
///
/// ## القاعدة (بسيطة ومطلقة)
/// تُعرض الشاشة إذا كان المستخدم حسابًا عاديًا (طالب/مدرّس) **ولا يملك
/// `avatarPreset` صالحًا** — أي:
///
/// | القيمة المحفوظة | النتيجة |
/// |---|---|
/// | غائبة (`null`) | تُعرض الشاشة |
/// | رقم داخل 0..29 | **دخول مباشر** بلا شاشة |
/// | رقم خارج المدى (40، ‑1، قيمة ملوّثة) | تُعرض الشاشة |
///
/// ## ما أُزيل بقرار صاحب المشروع
/// كان الشرط يستثني «الحسابات القديمة» عبر تاريخ فصل (`cutover`) وحقل
/// `createdAt`. أُلغي ذلك لأن التطبيق ما زال في مرحلة التجريب ولا توجد حسابات
/// مستخدمين قدامى حقيقية تُحمى؛ ووجود استثناء زمني كان يعني أن حسابًا **بلا
/// صورة** يمكنه تجاوز الشاشة لمجرد أن تاريخه قديم أو غير موجود — وهذا عكس
/// المطلوب. الآن **لا يُتجاوَز الحجب بسبب `createdAt` إطلاقًا**: الحقل موجود في
/// النموذج كمعلومة وصفية فقط، ولا يدخل في القرار.
///
/// ## الاستثناءات الباقية (وظيفية لا زمنية)
/// - **الجلسة التجريبية** (`isDemoAccount`): معاينة بلا حساب حقيقي ولا مستند
///   Firestore، فلا معنى لحجبها.
/// - **الدور الإداري**: لوحة الإدارة ليست حسابًا جديدًا ولا تُعرض لها شاشة
///   اختيار صورة (الدور الإداري لا يُمنح من التطبيق أصلًا).
///
/// ## ما لا تفعله هذه السياسة
/// - لا تُعيّن صورة تلقائيًا ولا عشوائيًا.
/// - لا تطلب عمرًا ولا جنسًا، ولا تفرض فئة على الطالب أو المدرّس.
abstract final class AvatarOnboardingPolicy {
  /// هل يجب حجب التطبيق خلف شاشة اختيار الصورة لهذا المستخدم؟
  static bool isRequired(AppUser? user) {
    if (user == null) {
      return false;
    }
    if (user.isDemoAccount) {
      return false;
    }
    if (!user.role.isEndUser) {
      return false;
    }
    return !hasValidPreset(user.avatarPreset);
  }

  /// هل القيمة المحفوظة اختيار صالح من الثلاثين؟
  ///
  /// نتحقق من المدى صراحةً بدل الاعتماد على `normalize` (التي تُصلح القيمة
  /// الخاطئة بصمت): الحساب الذي يحمل قيمة ملوّثة يجب أن يمرّ بالشاشة ليختار
  /// صورة حقيقية، لا أن يُلبَس صورة لم يطلبها.
  static bool hasValidPreset(int? preset) {
    if (preset == null) {
      return false;
    }
    return preset >= 0 && preset < AvatarPresets.count;
  }
}
